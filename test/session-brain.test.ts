import { test, before } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { Db } from '../src/db.ts';
import type { Ctx } from '../src/tools/common.ts';
import { ensureBrain } from '../src/tools/memory.ts';
import { filesServer, FILES_INSTRUCTIONS } from '../src/server.ts';
import { MAX_APPEND, MAX_NOTES_BYTES } from '../src/tools/session-brain.ts';

const brain = mkdtempSync(join(tmpdir(), 'brain-'));
process.env.BRAIN_DIR = brain;
const db = new Db(':memory:');
const ctx = { cfg: { machines: [], projects: [], endpoints: [], routing: [], agents: [] }, db } as unknown as Ctx;

const connect = async (caller: { session: string; machine: string } | null) => {
  const [a, b] = InMemoryTransport.createLinkedPair();
  await filesServer(ctx, caller).connect(a);
  const c = new Client({ name: 't', version: '0' });
  await c.connect(b);
  return c;
};
const call = async (c: Client, name: string, args: Record<string, unknown> = {}) => {
  const r = await c.callTool({ name, arguments: args }) as { isError?: boolean; content: { text: string }[] };
  return { err: !!r.isError, ...JSON.parse(r.content[0]!.text) } as { err: boolean; summary: string; [k: string]: any };
};
const gitLog = () => execFileSync('git', ['-C', brain, 'log', '--format=%s']).toString();

before(async () => {
  await ensureBrain(brain);
  db.upsertSession({ name: 'cc-alpha', machine: 'hub', project: 'alpha', status: 'idle', remote_control: 0 });
  db.upsertSession({ name: 'cc-noproj', machine: 'hub', project: '', status: 'idle', remote_control: 0 });
  mkdirSync(join(brain, 'projects/alpha/sub'), { recursive: true });
  mkdirSync(join(brain, 'projects/beta'), { recursive: true });
  writeFileSync(join(brain, 'projects/alpha/design.md'), 'alpha uses sqlite for storage\n');
  writeFileSync(join(brain, 'projects/beta/design.md'), 'beta secret plan: unobtanium\n');
  writeFileSync(join(brain, 'index.md'), '# index mentions unobtanium too\n');
  symlinkSync(join(brain, 'projects/beta'), join(brain, 'projects/alpha/sneaky'));
});

test('the session brain exposes read, search and append only (no write, no delete, no link)', async () => {
  const c = await connect({ session: 'cc-alpha', machine: 'hub' });
  const names = (await c.listTools()).tools.map((t) => t.name).sort();
  assert.deepEqual(names, ['file_list', 'file_revoke', 'file_share', 'memory_append', 'memory_read', 'memory_search']);
  assert.match(FILES_INSTRUCTIONS, /Keep the shared brain current without being asked/);
  assert.match(FILES_INSTRUCTIONS, /read, search and append only/);
});

test('append: goes to the own project notes.md with the session name, is committed, and builds up', async () => {
  const c = await connect({ session: 'cc-alpha', machine: 'hub' });
  const r = await call(c, 'memory_append', { text: 'Decision: use sqlite.' });
  assert.ok(!r.err, r.summary);
  assert.equal(r.summary, 'Added to projects/alpha/notes.md.');
  await call(c, 'memory_append', { text: 'Verified: tests pass.' });
  const notes = readFileSync(join(brain, 'projects/alpha/notes.md'), 'utf8');
  assert.match(notes, /### \d{4}-\d\d-\d\d \d\d:\d\d UTC · cc-alpha\nDecision: use sqlite\.\n/);
  assert.match(notes, /Verified: tests pass\./);
  assert.match(gitLog(), /memory_append: projects\/alpha\/notes\.md \(cc-alpha\)/);
  const sub = await call(c, 'memory_append', { text: 'Sub note.', path: 'sub/ideas.md' });
  assert.ok(!sub.err);
  assert.ok(existsSync(join(brain, 'projects/alpha/sub/ideas.md')));
});

test('append: size cap per note, markdown only, generated files protected', async () => {
  const c = await connect({ session: 'cc-alpha', machine: 'hub' });
  assert.ok(!(await call(c, 'memory_append', { text: 'x'.repeat(MAX_APPEND) })).err, 'exactly the cap is fine');
  const big = await call(c, 'memory_append', { text: 'x'.repeat(MAX_APPEND + 1) });
  assert.ok(big.err); assert.match(big.summary, /Too long/);
  for (const path of ['run.sh', 'data.json', 'noext']) assert.match((await call(c, 'memory_append', { text: 'a', path })).summary, /\.md files/, path);
  for (const path of ['context.md', 'log.md', 'links.md']) assert.match((await call(c, 'memory_append', { text: 'a', path })).summary, /generated by the orchestrator/, path);
  // a notes file that is already huge stops growing
  writeFileSync(join(brain, 'projects/alpha/huge.md'), 'y'.repeat(MAX_NOTES_BYTES + 1));
  assert.match((await call(c, 'memory_append', { text: 'a', path: 'huge.md' })).summary, /summarize it/);
});

test('scope: nothing outside projects/<project>/ can be appended, read or searched', async () => {
  const c = await connect({ session: 'cc-alpha', machine: 'hub' });
  for (const path of ['../beta/notes.md', '../../index.md', '../../.git/config', 'sub/../../beta/x.md', 'sneaky/x.md', '.git/x.md']) {
    const a = await call(c, 'memory_append', { text: 'pwn', path });
    assert.ok(a.err, `append ${path}`);
    const r = await call(c, 'memory_read', { path });
    assert.ok(r.err, `read ${path}`);
  }
  // an absolute-looking path is just relative to the project folder
  assert.ok(!(await call(c, 'memory_append', { text: 'a', path: '/etc/x.md' })).err);
  assert.ok(existsSync(join(brain, 'projects/alpha/etc/x.md')));
  assert.ok(!existsSync('/etc/x.md'));
  assert.ok(!existsSync(join(brain, 'projects/beta/notes.md')));
  assert.ok(!existsSync(join(brain, 'projects/beta/x.md')));
  // reading through the symlink to another project is refused, reading the own files works
  assert.match((await call(c, 'memory_read', { path: 'sneaky/design.md' })).summary, /outside your project folder|points outside/);
  assert.equal((await call(c, 'memory_read', { path: 'design.md' })).content, 'alpha uses sqlite for storage\n');
  assert.ok((await call(c, 'memory_read', { path: '.' })).entries.includes('design.md'));
  const found = await call(c, 'memory_search', { query: 'sqlite' });
  assert.ok(found.hits.some((h: { path: string }) => h.path === 'projects/alpha/design.md'));
  const other = await call(c, 'memory_search', { query: 'unobtanium' });
  assert.equal(other.hits.filter((h: { path: string }) => !h.path.startsWith('projects/alpha/')).length, 0, 'no hits outside the own project');
});

test('a session that is not identified, or has no project, has no brain access at all', async () => {
  for (const caller of [null, { session: 'cc-noproj', machine: 'hub' }, { session: 'cc-unknown', machine: 'hub' }]) {
    const c = await connect(caller);
    for (const [name, args] of [['memory_append', { text: 'a' }], ['memory_read', { path: '.' }], ['memory_search', { query: 'a' }]] as const) {
      const r = await call(c, name, args as Record<string, unknown>);
      assert.ok(r.err, `${caller?.session ?? 'null'} ${name}`);
      assert.match(r.summary, /no brain folder/);
    }
  }
});

test('the project comes from the session, not from an argument', async () => {
  const c = await connect({ session: 'cc-alpha', machine: 'hub' });
  const t = (await c.listTools()).tools.find((x) => x.name === 'memory_append')!;
  assert.deepEqual(Object.keys((t.inputSchema as { properties: object }).properties).sort(), ['path', 'text']);
});
